#!/usr/bin/env python
"""Build a writer voice profile from samples of the writer's own writing.

Samples: 3 or more .txt/.md files, ideally 1,500+ words in total, written by the
writer without AI help (pre-2023 texts or early drafts are safest), in the
register the profile is for. Remove quoted text by other people, code and
reference lists first. One profile per register works best (e.g. "papers" and
"blog").

The samples are cut into paragraph-aligned chunks of about 300 words, and the
surface and syntax layers (optionally the LM layer) are measured on each chunk.
The result is the writer's own band for every feature, plus countable habits:
spelling convention, dash glyphs, pronouns, sentence openers, paragraph size,
AI-list words the writer genuinely uses, recurring phrases.

Output directory (default ~/.deep-humanizer/profiles/NAME):
    profile.json   measured bands and habits (rewritten on every run)
    voice.md       the writer's style card; created from assets/voice_template.md on the
                   first run, afterwards only the block between the measured markers is
                   replaced, so the writer's own edits are kept
    samples/       copies of the samples (unless --no-copy), used for the style-embedding match

Keep profiles out of public repositories: they contain the writer's text.

Usage:
    python build_profile.py my_writing/ --name blog --register "Blog posts, first person"
    python build_profile.py my_papers/ --out ~/profiles/papers --lm
    python check.py draft.md --profile blog
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import shutil
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from hz_common import ASSETS, dump_json, model_id, read_text, strip_markup, words  # noqa: E402
import voice_profile as vp  # noqa: E402


def recurring_phrases(texts: list[str], stop: set[str], top: int = 20) -> list[dict]:
    per_file = []
    for t in texts:
        toks = [w.lower() for w in words(strip_markup(t)) if not any(ch.isdigit() for ch in w)]
        grams = Counter()
        for n in (2, 3, 4):
            for i in range(len(toks) - n + 1):
                g = tuple(toks[i:i + n])
                if all(w in stop for w in g) or g[0] in ("and", "or") or g[-1] in ("the", "a", "an", "and", "of", "to"):
                    continue
                grams[g] += 1
        per_file.append(grams)
    total, files = Counter(), Counter()
    for g in per_file:
        total.update(g)
        files.update(set(g))
    keep = [(g, c) for g, c in total.items() if c >= 3 and files[g] >= 2]
    keep.sort(key=lambda x: (-len(x[0]) * x[1], x[0]))
    out: list[tuple] = []
    for g, c in keep:
        s = " ".join(g)
        if any(s in " ".join(o) and c <= oc for o, oc in out):
            continue
        out.append((g, c))
        if len(out) >= top:
            break
    return [{"phrase": " ".join(g), "count": c, "files": files[g]} for g, c in out]


def _fmt(v: float, unit: str) -> str:
    if unit == "share":
        return f"{100 * v:.0f}%"
    if unit in ("index", "count"):
        return f"{v:.0f}"
    return f"{v:.1f}"


def measured_block(P: dict) -> str:
    B, H = P["bands"], P["habits"]
    L = [vp.MEASURED_START, "## Measured from my samples", "",
         f"Regenerated by `build_profile.py` on {P['created']} from {P['n_files']} files ({P['n_words']} words, "
         f"{P['n_chunks']} chunks of about {P['chunk_words']} words). Do not edit inside this block; edit the sections "
         "above. The agent uses these numbers as the target band for this writer.", ""]
    if P.get("warnings"):
        L += ["Warnings: " + " ".join(P["warnings"]), ""]
    L += ["| Habit | My median | My usual range (p10-p90) |", "|---|---|---|"]
    for f, (label, unit, _, _) in vp.VOICE_FEATURES.items():
        b = B.get(f)
        if b:
            L.append(f"| {label} | {_fmt(b['median'], unit)} | {_fmt(b['p10'], unit)}-{_fmt(b['p90'], unit)} |")
    L.append("")
    sp = H["spelling"]
    ex = sp["british_examples"] if sp["convention"] == "British" else sp["american_examples"]
    L.append(f"- Spelling: {sp['convention']} ({sp['british']} British vs {sp['american']} American forms"
             + (f"; e.g. {', '.join(ex[:5])}" if ex and sp["convention"] in ("British", "American") else "") + ")")
    dg = H["dash_glyphs"]
    L.append(f"- Dash glyphs: em dash {dg['em_dash']}, spaced en dash {dg['spaced_en_dash']}, spaced hyphen "
             f"{dg['spaced_hyphen']}, double hyphen {dg['double_hyphen']}")
    L.append(f"- Pronouns per 1k words: 'I' {H['i_per_1k']:.1f}, 'we/our/us' {H['we_per_1k']:.1f}")
    L.append(f"- Paragraphs: about {H['sentences_per_paragraph']:.1f} sentences and {H['words_per_paragraph']:.0f} words")
    top_open = ", ".join(f"{w} ({c})" for w, c in list(H["openers"].items())[:10])
    L.append(f"- Most common sentence openers: {top_open}")
    conn = sorted(H["connectives"].items(), key=lambda kv: -kv[1])[:10]
    if conn:
        L.append("- Connectives I open sentences with: " + ", ".join(f"{c} ({n})" for c, n in conn))
    never = [c for c in vp.LLM_FAVOURITE_OPENERS if not H["connectives"].get(c)]
    if H["n_sentences"] >= 40 and never:
        L.append("- LLM-favourite openers that never appear in my samples: " + ", ".join(never))
    va = P["vocab_in_samples"]
    if va:
        L.append("- AI-list words found in my samples: " + ", ".join(
            f"{t} ({d['count']}x, {d['files']} files)" for t, d in sorted(va.items(), key=lambda kv: -kv[1]["count"])[:20]))
    if P["recurring_phrases"]:
        L.append("- Recurring phrases (topic terms included; the habits are the ones worth keeping): " + ", ".join(
            f"\"{r['phrase']}\" ({r['count']})" for r in P["recurring_phrases"][:15]))
    fw = P.get("function_words")
    if fw:
        L.append(f"- Function-word profile: top {len(fw['words'])} words recorded for the distance check")
    L += ["", vp.MEASURED_END]
    return "\n".join(L)


def write_voice_md(path: Path, P: dict, register: str | None, mine: list[str]) -> str:
    block = measured_block(P)
    if path.exists():
        md = path.read_text(encoding="utf-8")
        if vp.MEASURED_START in md and vp.MEASURED_END in md:
            i, j = md.index(vp.MEASURED_START), md.index(vp.MEASURED_END) + len(vp.MEASURED_END)
            md = md[:i] + block + md[j:]
        else:
            md = md.rstrip() + "\n\n" + block + "\n"
        path.write_text(md, encoding="utf-8")
        return "updated measured block"
    t = (ASSETS / "voice_template.md").read_text(encoding="utf-8")
    t = t.replace("# Voice profile\n", f"# Voice profile: {P['name']}\n", 1)
    t = t.replace("<!-- register -->\n", f"- {register}\n" if register else "", 1)
    if mine:
        t = t.replace("<!-- mine -->\n", "".join(f"- {w}\n" for w in mine)
                      + "<!-- pre-filled from your samples by build_profile.py: delete any you do not want -->\n", 1)
    else:
        t = t.replace("<!-- mine -->\n", "", 1)
    i, j = t.index(vp.MEASURED_START), t.index(vp.MEASURED_END) + len(vp.MEASURED_END)
    path.write_text(t[:i] + block + t[j:], encoding="utf-8")
    return "created"


def inside_git_repo(p: Path) -> Path | None:
    for q in [p, *p.parents]:
        if (q / ".git").exists():
            return q
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("samples", help="directory of the writer's own texts (.txt/.md)")
    ap.add_argument("--name", default="default", help="profile name (default 'default')")
    ap.add_argument("--out", help="profile directory (default ~/.deep-humanizer/profiles/NAME)")
    ap.add_argument("--register", help="one line describing the register, written into a new voice.md")
    ap.add_argument("--chunk-words", type=int, default=300)
    ap.add_argument("--no-copy", action="store_true", help="reference the samples in place instead of copying them")
    ap.add_argument("--lm", action="store_true", help="also measure LM-layer features per chunk (slow)")
    ap.add_argument("--force", action="store_true", help="replace a samples/ folder that holds a different set of files")
    a = ap.parse_args()

    src = Path(a.samples).expanduser().resolve()
    if not src.is_dir():
        raise SystemExit(f"not a directory: {src}")
    files = vp.sample_files(src)
    if not files:
        raise SystemExit(f"no .txt/.md files in {src}")
    out = Path(a.out).expanduser().resolve() if a.out else (vp.profile_home() / a.name).resolve()
    name = a.name if (a.name != "default" or not a.out) else out.name
    texts, normalised = [], []
    for f in files:
        t, changed = vp.normalise_paragraphs(read_text(str(f)))
        texts.append(t)
        if changed:
            normalised.append(f.name)
    n_words = sum(len(words(strip_markup(t))) for t in texts)

    warnings = []
    if normalised:
        warnings.append(f"{len(normalised)} file(s) had no blank lines between paragraphs; each line was treated as a "
                        f"paragraph ({', '.join(normalised[:5])}).")
    if len(files) < 3:
        warnings.append(f"Only {len(files)} sample file(s); 3 or more give a usable band and the style-embedding match.")
    if n_words < 1500:
        warnings.append(f"Only {n_words} words; 1,500+ give stable bands.")
    out.mkdir(parents=True, exist_ok=True)
    repo = inside_git_repo(out)
    if repo:
        print(f"[profile] WARNING: {out} is inside the git repository {repo}. The profile contains your writing; "
              "make sure it is git-ignored (the skill's .gitignore covers profiles/).", file=sys.stderr)

    # samples
    dest = out / "samples"
    if a.no_copy:
        samples_dir = str(src)
    elif dest.exists() and src == dest.resolve():
        samples_dir = "samples"
    else:
        if dest.exists():
            old = {f.name for f in vp.sample_files(dest)}
            new = {f.name for f in files}
            if old and old != new:
                if not a.force:
                    raise SystemExit(f"{dest} already holds a different set of samples "
                                     f"(only there: {sorted(old - new)[:5]}; new: {sorted(new - old)[:5]}). "
                                     "Use --force to replace them, or a different --name/--out.")
                for f in vp.sample_files(dest):
                    if f.name not in new:
                        f.unlink()
        dest.mkdir(exist_ok=True)
        for f in files:
            shutil.copy2(f, dest / f.name)
        samples_dir = "samples"

    # per-chunk features
    import check
    import stylometry
    import surface_scan
    vocab = surface_scan.load_vocab(None)
    rows, fw, per_file = [], [], []
    vocab_terms: dict[str, dict] = defaultdict(lambda: {"count": 0, "files": 0})
    for f, t in zip(files, texts):
        chunks = vp.chunk_text(t, a.chunk_words)
        per_file.append({"file": f.name, "words": len(words(strip_markup(t))), "chunks": len(chunks)})
        hits = surface_scan.scan(t, vocab)["ai_vocab_hits"]
        for term, c in hits.items():
            vocab_terms[term]["count"] += c
            vocab_terms[term]["files"] += 1
        for c in chunks:
            res = {"surface": surface_scan.scan(c, vocab)}
            st = stylometry.features(c)
            res["stylometry"] = st
            if a.lm:
                import lm_signals
                res["lm"] = lm_signals.score(c, performer=None)
            row = check.flatten(res)
            row.update(vp.extra_features(c))
            rows.append(row)
            fw.append(st["function_word_profile"])
        print(f"[profile] {f.name}: {per_file[-1]['words']} words, {len(chunks)} chunks", file=sys.stderr)
    if len(rows) < 3:
        warnings.append(f"Only {len(rows)} chunk(s) of {a.chunk_words} words; bands need 3+ (use more text or a "
                        "smaller --chunk-words, not below 150).")

    joined = "\n\n".join(texts)
    habits = vp.text_habits(joined)
    habits.pop("quotes", None)
    P = {
        "version": 1, "name": name, "register": a.register, "created": dt.date.today().isoformat(),
        "samples_dir": samples_dir, "n_files": len(files), "n_words": n_words, "n_chunks": len(rows),
        "chunk_words": a.chunk_words, "files": per_file,
        "models": {"spacy": "en_core_web_sm", **({"observer": model_id("observer")} if a.lm else {})},
        "bands": vp.bands(rows), "function_words": vp.function_word_stats(fw), "habits": habits,
        "vocab_in_samples": dict(vocab_terms), "recurring_phrases": recurring_phrases(texts, surface_scan.STOPWORDS),
        "warnings": warnings,
    }
    dump_json(P, str(out / "profile.json"))
    mine = sorted(t for t, d in vocab_terms.items() if d["files"] >= 2 or d["count"] >= 3)
    action = write_voice_md(out / "voice.md", P, a.register, mine)
    print(json.dumps({"profile": str(out), "name": name, "files": len(files), "words": n_words, "chunks": len(rows),
                      "voice_md": action, "spelling": habits["spelling"]["convention"], "warnings": warnings}, indent=1))
    print(f"\nNext: edit {out / 'voice.md'} (registers, habits, phrases you avoid), then\n"
          f"  python {Path(__file__).parent / 'check.py'} draft.md --profile {out}")


if __name__ == "__main__":
    main()
